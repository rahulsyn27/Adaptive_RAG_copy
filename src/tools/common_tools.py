"""
Common tools for document processing.
"""

from langchain_core.prompts import PromptTemplate

from src.llms.groq import llm


def enhance_description_with_llm(description: str) -> str:
    """
    Enhance a document description using LLM.

    Args:
        description: The original document description.

    Returns:
        Enhanced description generated by LLM.
    """
    prompt = PromptTemplate(
        template="""
        You are given a brief description of a document. 
        Enhance this description to be more detailed and comprehensive, 
        suitable for use as a tool description in a RAG system.
        
        Original description: {description}
        
        Enhanced description:
        """,
        input_variables=["description"]
    )
    chain = prompt | llm
    result = chain.invoke({"description": description})
    return result.content